// Writes supabase/seed/sudoku_puzzles.sql: the bundled puzzles, ready to paste
// into the Supabase SQL editor after the migration. Safe to run more than once
// (existing rows are left alone).
//
//   node scripts/sudoku-seed.mjs

import { writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { PUZZLES } from '../app/components/Sudoku/puzzles.js';
import { canonicalKey } from '../app/components/Sudoku/engine/canonical.js';
import { countSolutions } from '../app/components/Sudoku/engine/solver.js';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const out = join(root, 'supabase', 'seed', 'sudoku_puzzles.sql');

const q = v => (v == null ? 'null' : `'${String(v).replace(/'/g, "''")}'`);

const rows = PUZZLES.map(p => {
  const r = countSolutions(p, 2);
  if (r.count !== 1 || r.solution !== p.solution) throw new Error(`${p.id} doesn't have exactly one solution`);
  const cages = p.cages && JSON.stringify(p.cages.map(c => ({ sum: c.sum, cells: c.cells })));
  return `  (${[
    q(p.id), q(p.kind), q(p.difficulty), q(p.name),
    q(p.givens), cages ? `${q(cages)}::jsonb` : 'null', q(p.solution),
    q(canonicalKey(p)), q('bundled'),
  ].join(', ')})`;
});

const sql = `-- Generated by scripts/sudoku-seed.mjs. The puzzles bundled with the site.
-- Positions are left to the database, which numbers them after any already there.
-- (scripts/sudoku-import.mjs does the same and also imports more puzzles.)
insert into public.sudoku_puzzles
  (id, kind, difficulty, name, givens, cages, solution, canonical, source)
values
${rows.join(',\n')}
on conflict do nothing;
`;

mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, sql);
console.log(`Wrote ${rows.length} puzzles to ${out}`);
